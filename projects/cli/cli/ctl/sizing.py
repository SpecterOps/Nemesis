"""File-enrichment replicas sized to the host's CPUs (prod only).

One file-enrichment process tops out at about one core: its workflows run on a single asyncio event loop. Extra
replicas, each a file-enrichment container with its own Dapr sidecar under the same app ID, share the work. Measured
on 8 CPUs (996 workflows): 2 replicas finished 31% faster than 1 and 3 replicas 41% faster, while raising one
replica's workflow slots from 5 to 15 gained only 13%. Under load a replica with its sidecar uses about one core, and
the shared services (Postgres, RabbitMQ, SeaweedFS, document conversion) about two; Postgres is the next limit.

The replicas are written to a compose override file kept outside the checkout (it holds absolute paths), so that
stop/clean/status/logs include the replicas the last start created.
"""

import hashlib
import json
import os
from collections.abc import Mapping
from pathlib import Path

REPLICAS_ENVVAR = "NEMESIS_ENRICHMENT_REPLICAS"
CPUS_ENVVAR = "NEMESIS_CPUS"
AUTO = "auto"
MAX_AUTO_REPLICAS = 4  # not measured beyond 3; Postgres limits more replicas
SHARED_SERVICES_CPUS = 2
CPUS_PER_REPLICA = 2  # a replica, its sidecar, and the extra work it sends to the shared services
OVERRIDE_NAME = "compose.replicas.yaml"
# The image `compose.prod.build.yaml` builds for file-enrichment (the project is named `nemesis` in compose.yaml)
BUILT_IMAGE = "nemesis-file-enrichment"


class SizingError(ValueError):
    """An invalid replica count or CPU override."""


def detect_cpus(environ: Mapping[str, str]) -> int:
    """CPUs available to Nemesis: $NEMESIS_CPUS, else the CPUs this process may run on."""
    if value := environ.get(CPUS_ENVVAR, "").strip():
        try:
            cpus = int(value)
        except ValueError:
            cpus = 0
        if cpus < 1:
            raise SizingError(f"{CPUS_ENVVAR} must be a positive whole number, got '{value}'.")
        return cpus
    return os.process_cpu_count() or os.cpu_count() or 1


def auto_replicas(cpus: int) -> int:
    """1 replica up to 5 CPUs, 2 at 6-7, 3 at 8-9, then 4."""
    return max(1, min(MAX_AUTO_REPLICAS, (cpus - SHARED_SERVICES_CPUS) // CPUS_PER_REPLICA))


def parse_replicas(value: object) -> int | None:
    """ "auto" -> None (size to the CPUs), otherwise a whole number of at least 1 (an int, or a string of one)."""
    count = 0
    if isinstance(value, str):
        text = value.strip()
        if text.lower() == AUTO:
            return None
        count = int(text) if text.isdecimal() else 0
    elif isinstance(value, int) and not isinstance(value, bool):
        count = value
    if count < 1:
        raise SizingError(f"file-enrichment replicas must be '{AUTO}' or a whole number of at least 1, got {value!r}.")
    return count


def override_path(project_dir: Path, environ: Mapping[str, str]) -> Path:
    """Per-checkout location: $XDG_STATE_HOME/nemesis/deployments/<checkout hash>/compose.replicas.yaml."""
    base = environ.get("XDG_STATE_HOME") or str(Path(environ.get("HOME") or Path.home()) / ".local" / "state")
    key = hashlib.sha256(str(project_dir.resolve()).encode()).hexdigest()[:12]
    return Path(base) / "nemesis" / "deployments" / key / OVERRIDE_NAME


def replica_services(replicas: int) -> list[str]:
    """Services the override adds: file-enrichment-2 and file-enrichment-2-dapr, ... up to `replicas`."""
    return [name for n in range(2, replicas + 1) for name in (f"file-enrichment-{n}", f"file-enrichment-{n}-dapr")]


def render_override(project_dir: Path, replicas: int, *, build: bool) -> str:
    """Compose override adding replicas 2..N of file-enrichment, each with its own Dapr sidecar."""
    if replicas < 2:
        raise ValueError("an override is only needed for 2 or more replicas")
    compose_file = json.dumps(str(project_dir.resolve() / "compose.yaml"))  # a JSON string is a valid YAML scalar
    lines = [
        f"# Generated by `nemesis start` for {replicas} file-enrichment replicas; rewritten on every start.",
        "services:",
    ]
    for n in range(2, replicas + 1):
        app = f"file-enrichment-{n}"
        lines += [
            f"  {app}:",
            f"    extends: {{ file: {compose_file}, service: file-enrichment }}",
        ]
        if build:
            # Run the image built for file-enrichment instead of building (or pulling) it again
            lines += [f"    image: {BUILT_IMAGE}", "    pull_policy: never"]
        lines += [
            f"  {app}-dapr:",
            f"    extends: {{ file: {compose_file}, service: file-enrichment-dapr }}",
            "    depends_on: !override",
            f"      {app}: {{ condition: service_started }}",
            "      scheduler: { condition: service_started }",
            "      rabbitmq: { condition: service_healthy }",
            f'    network_mode: "service:{app}"',
        ]
    return "\n".join(lines) + "\n"
